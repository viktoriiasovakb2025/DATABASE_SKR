from sqlalchemy import Column, ForeignKey, Integer, Table

from database_skr.database import Base

student_subjects = Table(
    "student_subjects",
    Base.metadata,
    Column(
        "student_id",
        Integer,
        ForeignKey("students.id", ondelete="CASCADE"),
        primary_key=True,
    ),
    Column(
        "subject_id",
        Integer,
        ForeignKey("subjects.id", ondelete="CASCADE"),
        primary_key=True,
    ),
)
